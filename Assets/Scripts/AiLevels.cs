using UnityEngine;

/// <summary>
/// Уровни ИИ аниматроников для каждой ночи.
/// aiNum[0] = Фреддо, [1] = Бонита, [2] = Чика-Лока, [3] = Фокси-Рекс, [4] = GLITCH
/// 
/// Балансировка по ночам:
/// Ночь 1: только Фреддо активен — [1, 0, 0, 0, 0]
/// Ночь 2: Фреддо + Бонита        — [2, 3, 0, 0, 0]
/// Ночь 3: тройка                  — [4, 4, 3, 0, 0]
/// Ночь 4: все + Фокси-Рекс        — [5, 5, 5, 4, 0]
/// Ночь 5: все + GLITCH            — [8, 7, 7, 6, 3]
/// Ночь 6: бонусная                — [12, 12, 10, 10, 8]
/// Ночь 7: кастомная — управляется AiSelector (PlayerPrefs)
/// </summary>
public class AiLevels : MonoBehaviour
{
    [Tooltip("Уровень ИИ каждого аниматроника: [Фреддо, Бонита, Чика-Лока, Фокси-Рекс, GLITCH]")]
    public int[] aiNum = new int[5] { 0, 0, 0, 0, 0 };
}
